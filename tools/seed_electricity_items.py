def build_choices(it: dict) -> list[dict]:
    """선지 5개를 만든다. 합답형은 combo, 정답형은 text."""
    if it.get("qtype") == "서술형":
        return []
    if it.get("combo"):
        return [{"ord": i + 1, "text": "", "combo": json.dumps(c, ensure_ascii=False),
                 "is_answer": int(i + 1 == it["ans"])} for i, c in enumerate(COMBO5)]
    return [{"ord": i + 1, "text": t, "combo": "", "is_answer": int(i + 1 == it["ans"])}
            for i, t in enumerate(it["choices"])]


def answer_text(it: dict) -> str:
    if it.get("qtype") == "서술형":
        return it.get("answer", "")
    return "①②③④⑤"[it["ans"] - 1]


def bogi_json(it: dict) -> str:
    return json.dumps(
        [{"label": BOGI_LABELS[i], "text": t} for i, t in enumerate(it.get("bogi", []))],
        ensure_ascii=False)


